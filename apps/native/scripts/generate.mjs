// Writes verify/src/generated.rs from @pnw/brand and @pnw/config, or, without --write, fails when
// the committed file differs. The native verifier takes the product's name, the release keys,
// the program ids and the explorer from here, never written out by hand (CLAUDE.md: the brand
// lives only in packages/brand; INV-12: program names only from @pnw/config), as
// apps/desktop/scripts/tauri_config.mjs does for the desktop app. Plain Node runs it: the
// TypeScript it imports is stripped of types on load (Node 22.18+). No install needed.
//
//   node apps/native/scripts/generate.mjs --write
//   node apps/native/scripts/generate.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// The brand and the config read a few NEXT_PUBLIC_* variables for the website's builds. The
// native app is built from the defaults alone, so a machine's settings never change the file.
for (const name of Object.keys(process.env)) if (name.startsWith("NEXT_PUBLIC_")) delete process.env[name];

const ROOT = join(import.meta.dirname, "..", "..", "..");
const { BRAND, CREDIT, releaseKeys, RELEASE_KEY_FIXTURE } = await import(join(ROOT, "packages/brand/src/index.ts"));
const { PROGRAMS, NATIVE_PROGRAM } = await import(join(ROOT, "packages/config/src/programs.ts"));
const { ENV } = await import(join(ROOT, "packages/config/src/env.ts"));

export const FILE = join(import.meta.dirname, "..", "verify", "src", "generated.rs");
export const HEADER = "// Generated by apps/native/scripts/generate.mjs from @pnw/brand and @pnw/config.";

/** A Rust string literal: the escapes Rust reads, everything else as itself. */
function str(value) {
  if (typeof value !== "string") throw new Error(`Expected a string, got ${typeof value}`);
  let out = '"';
  for (const ch of value) {
    const code = ch.codePointAt(0);
    if (ch === "\\") out += "\\\\";
    else if (ch === '"') out += '\\"';
    else if (ch === "\n") out += "\\n";
    else if (ch === "\r") out += "\\r";
    else if (ch === "\t") out += "\\t";
    else if (code < 0x20 || code === 0x7f) out += `\\u{${code.toString(16)}}`;
    else out += ch;
  }
  return `${out}"`;
}

const constName = (key) => key.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
const modName = (key) => {
  if (!/^[a-z][a-z0-9_]*$/.test(key)) throw new Error(`Not a module name: ${key}`);
  return key;
};

function colour(hex) {
  if (!/^#[0-9a-f]{6}$/.test(hex)) throw new Error(`Not a colour: ${hex}`);
  return `0x${hex.slice(1)}`;
}

function releaseKey(k) {
  return `ReleaseKey { id: ${str(k.id)}, public_key: ${str(k.publicKey)} }`;
}

function programs(obj, indent) {
  const pad = "    ".repeat(indent);
  const lines = [];
  for (const [key, value] of Object.entries(obj)) {
    if (typeof value === "string") lines.push(`${pad}pub const ${constName(key)}: &str = ${str(value)};`);
    else {
      lines.push(`${pad}pub mod ${modName(key)} {`);
      lines.push(...programs(value, indent + 1));
      lines.push(`${pad}}`);
    }
  }
  return lines;
}

export function generated() {
  const colours = Object.entries(BRAND.colors).map(([k, v]) => `        pub const ${constName(k)}: u32 = ${colour(v)};`);
  return [
    HEADER,
    "// Never edit it by hand: change the source and run `node apps/native/scripts/generate.mjs --write`.",
    "// CI fails when this file differs from what the script makes (.github/workflows/native.yml).",
    "",
    "/// The product's name, words and colours, and the keys a release is signed with (@pnw/brand).",
    "pub mod brand {",
    `    pub const NAME: &str = ${str(BRAND.name)};`,
    `    pub const TAGLINE: &str = ${str(BRAND.tagline)};`,
    `    pub const SOURCE_URL: &str = ${str(BRAND.sourceUrl)};`,
    `    pub const LICENCE: &str = ${str(BRAND.licence)};`,
    `    pub const CREDIT_TEXT: &str = ${str(CREDIT.text)};`,
    `    pub const CREDIT_URL: &str = ${str(CREDIT.url)};`,
    `    pub const COPYRIGHT: &str = ${str(CREDIT.copyright)};`,
    "",
    "    /// The brand's colours as 0xRRGGBB.",
    "    pub mod colors {",
    ...colours,
    "    }",
    "",
    "    /// A release public key: its id (the first 16 hex of the SHA-256 of the raw key) and the raw",
    "    /// 32-byte Ed25519 key in base64.",
    "    #[derive(Clone, Copy, Debug, PartialEq, Eq)]",
    "    pub struct ReleaseKey {",
    "        pub id: &'static str,",
    "        pub public_key: &'static str,",
    "    }",
    "",
    "    /// The keys a release of this app must be signed with. Empty until the operator publishes one.",
    `    pub const RELEASE_KEYS: &[ReleaseKey] = &[${releaseKeys.map(releaseKey).join(", ")}];`,
    "",
    "    /// For tests only, never trusted: the key that signed scripts/release/fixture.",
    `    pub const RELEASE_KEY_FIXTURE: ReleaseKey = ${releaseKey(RELEASE_KEY_FIXTURE)};`,
    "}",
    "",
    "/// The network, the explorer and the program ids (@pnw/config), at their defaults.",
    "pub mod config {",
    `    pub const NETWORK: &str = ${str(ENV.NETWORK)};`,
    `    pub const ALEO_ENDPOINT: &str = ${str(ENV.ALEO_ENDPOINT)};`,
    `    pub const NATIVE_PROGRAM: &str = ${str(NATIVE_PROGRAM)};`,
    "",
    "    pub mod programs {",
    ...programs(PROGRAMS, 2),
    "    }",
    "}",
    "",
  ].join("\n");
}

const text = generated();
if (process.argv.includes("--write")) {
  writeFileSync(FILE, text);
  console.log(`wrote ${FILE}`);
} else {
  let current = "";
  try {
    current = readFileSync(FILE, "utf8");
  } catch {
    // missing: reported below
  }
  if (current !== text) {
    console.error("apps/native/verify/src/generated.rs differs from @pnw/brand and @pnw/config: run node apps/native/scripts/generate.mjs --write");
    process.exit(1);
  }
  console.log("apps/native/verify/src/generated.rs matches @pnw/brand and @pnw/config");
}
